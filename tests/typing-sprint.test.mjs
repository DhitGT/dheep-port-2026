import test from 'node:test'
import assert from 'node:assert/strict'
import { createTypingSprint, insertedRange } from '../utils/typingSprint.js'

test('timer waits for typing and stops at 30 seconds', () => {
  const game = createTypingSprint(() => 0)
  game.tick(5000)
  assert.equal(game.state.elapsed, 0)
  game.input('c')
  game.tick(10000)
  assert.equal(game.stats().remaining, 20)
  game.tick(25000)
  assert.equal(game.state.phase, 'finished')
  assert.equal(game.state.elapsed, 30000)
  game.input('code ')
  assert.equal(game.state.completed, 0)
})
test('commands preserve internal spaces, credit correct prefixes and submit only as a complete line', () => {
  const game = createTypingSprint(() => 0)
  game.input('git ')
  assert.equal(game.state.draft, 'git ')
  assert.equal(game.state.completed, 0)
  assert.equal(game.stats().score, 4)
  assert.equal(game.submit(), false)
  game.input('git status')
  assert.equal(game.submit(), true)
  assert.equal(game.state.completed, 1)
  assert.equal(game.state.confirmedChars, 11)
  const length = game.state.words[0].length + 1
  game.input(game.state.words[0])
  assert.equal(game.submit(), true)
  game.tick(30000)
  assert.equal(game.stats().wpm, Math.round((11 + length) / 2.5))
  assert.equal(game.stats().accuracy, 100)
  assert.equal(game.stats().score, 11 + length)
})
test('fixing mistakes does not erase accuracy penalties or create credit for deleted text', () => {
  const game = createTypingSprint(() => 0)
  game.input('g!t status')
  assert.equal(game.submit(), false)
  game.input('git status')
  game.submit()
  assert.equal(game.state.completed, 1)
  assert.equal(game.state.attempts, 11)
  assert.equal(game.state.errors, 1)
  assert.equal(game.stats().accuracy, 90.9)
  assert.equal(game.stats().score, 9)
  assert.deepEqual(game.state.troubleWords, ['git status'])
  assert.deepEqual(insertedRange('code', 'cod'), { start: 3, text: '' })
})
test('difficulty increases and resetting clears the entire session', () => {
  const game = createTypingSprint(() => 0)
  for (let i = 0; i < 20; i++) { game.input(game.state.words[0]); game.submit() }
  assert.equal(game.stats().level, 2)
  assert.ok(game.state.words[0].length >= 8)
  assert.equal(game.state.bestStreak, 20)
  game.reset()
  assert.equal(game.state.completed, 0)
  assert.equal(game.state.attempts, 0)
  assert.equal(game.stats().score, 0)
  assert.equal(game.state.phase, 'ready')
})

test('AI prompt mode uses long English software briefs and credits an unfinished prompt', () => {
  const game = createTypingSprint(() => 0)
  game.reset('prompts')
  assert.equal(game.state.mode, 'prompts')
  assert.ok(game.state.words.every(text => text.length > 70 && text.includes(' ') && text.endsWith('.')))
  const target = game.state.words[0]
  game.input(target.slice(0, 45))
  game.tick(30000)
  assert.equal(game.stats().score, 45)
  assert.equal(game.stats().wpm, 18)
  assert.equal(game.state.completed, 0)
  game.reset('code')
  assert.equal(game.state.mode, 'code')
  assert.equal(game.state.words[0], 'git status')
})
