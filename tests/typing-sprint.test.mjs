import test from 'node:test'
import assert from 'node:assert/strict'
import { createTypingSprint, insertedRange } from '../utils/typingSprint.js'

test('timer waits for typing and stops at 30 seconds', () => {
  const game = createTypingSprint(() => 0)
  game.tick(5000)
  assert.equal(game.state.elapsed, 0)
  game.input('c')
  game.tick(10000)
  assert.equal(game.stats().remaining, 20)
  game.tick(25000)
  assert.equal(game.state.phase, 'finished')
  assert.equal(game.state.elapsed, 30000)
  game.input('code ')
  assert.equal(game.state.completed, 0)
})
test('only completed correct words earn WPM and score; Space and Enter both confirm', () => {
  const game = createTypingSprint(() => 0)
  game.input('code')
  assert.equal(game.stats().score, 0)
  game.input('code ')
  assert.equal(game.state.completed, 1)
  assert.equal(game.state.confirmedChars, 5)
  game.input(game.state.words[0])
  assert.equal(game.submit(), true)
  game.tick(30000)
  assert.equal(game.stats().wpm, 4)
  assert.equal(game.stats().accuracy, 100)
  assert.equal(game.stats().score, 10)
})
test('fixing mistakes does not erase accuracy penalties or create credit for deleted text', () => {
  const game = createTypingSprint(() => 0)
  game.input('cxde')
  assert.equal(game.submit(), false)
  game.input('code')
  game.submit()
  assert.equal(game.state.completed, 1)
  assert.equal(game.state.attempts, 5)
  assert.equal(game.state.errors, 1)
  assert.equal(game.stats().accuracy, 80)
  assert.equal(game.stats().score, 3)
  assert.deepEqual(game.state.troubleWords, ['code'])
  assert.deepEqual(insertedRange('code', 'cod'), { start: 3, text: '' })
})
test('difficulty increases and resetting clears the entire session', () => {
  const game = createTypingSprint(() => 0)
  for (let i = 0; i < 20; i++) game.input(`${game.state.words[0]} `)
  assert.equal(game.stats().level, 2)
  assert.ok(game.state.words[0].length >= 8)
  assert.equal(game.state.bestStreak, 20)
  game.reset()
  assert.equal(game.state.completed, 0)
  assert.equal(game.state.attempts, 0)
  assert.equal(game.stats().score, 0)
  assert.equal(game.state.phase, 'ready')
})
