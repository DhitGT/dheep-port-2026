import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) {
  test(`typing sprint rewards speed and accuracy and finishes correctly at ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/')
    await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
    await page.getByRole('tab', { name: /Typing Sprint/ }).click()
    if (width < 800) await expect(page.locator('.typing-board')).toBeHidden()
    await page.clock.install({ time: new Date('2026-10-16T00:00:00Z') })
    await page.clock.pauseAt(new Date('2026-10-16T00:00:01Z'))
    await page.getByRole('button', { name: 'Play Typing Sprint', exact: true }).click()
    const field = page.getByRole('textbox', { name: 'Type the highlighted word' })
    await expect(field).toBeFocused()
    await expect(field).toHaveAttribute('autocapitalize', 'off')
    await expect(field).toHaveAttribute('autocorrect', 'off')
    await page.clock.fastForward(5000)
    await expect(page.getByTestId('typing-time')).toHaveText('30s')
    const word = (await page.locator('.typing-target-word').getAttribute('aria-label'))!
    await field.pressSequentially(`${word} `)
    await expect(field).toHaveValue('')
    await expect(page.getByTestId('typing-score')).not.toHaveText('0')
    await page.clock.fastForward(1000)
    await expect(page.getByTestId('typing-wpm')).not.toHaveText('0')
    const next = (await page.locator('.typing-target-word').getAttribute('aria-label'))!
    await field.pressSequentially('!')
    await field.press('Enter')
    await expect(page.locator('.typing-target-word')).toHaveAttribute('aria-label', next)
    await field.press('Backspace')
    await field.pressSequentially(next)
    await field.press('Enter')
    expect(Number((await page.getByTestId('typing-accuracy').textContent())!.replace('%', ''))).toBeLessThan(100)
    await field.dispatchEvent('paste')
    await expect(page.locator('.typing-feedback')).toContainText('Use your keyboard')
    const time = await page.getByTestId('typing-time').textContent()
    await page.getByRole('tab', { name: /Color Match/ }).click()
    await page.clock.fastForward(5000)
    await page.getByRole('tab', { name: /Typing Sprint/ }).click()
    expect(await page.getByTestId('typing-time').textContent()).toBe(time)
    await field.focus()
    if (width < 800) {
      await expect(page.locator('.typing-menu')).toBeHidden()
      for (const tab of await page.getByRole('tab').all()) await expect(tab).toBeVisible()
      await expect(page.locator('.typing-hud')).toBeVisible()
    }
    await page.clock.fastForward(31000)
    await expect(page.locator('.typing-sprint-game')).toHaveAttribute('data-phase', 'finished')
    await expect(page.getByTestId('typing-final-wpm')).toBeVisible()
    expect(await page.evaluate(() => Number(localStorage.getItem('portfolio.typing-sprint.best')))).toBeGreaterThan(0)
    await page.locator('.typing-board').screenshot({ path: `../.tools/typing-result-${width}.png` })
    await page.getByRole('button', { name: 'Run another sprint' }).click()
    await expect(page.getByTestId('typing-score')).toHaveText('0')
    await expect(page.getByTestId('typing-time')).toHaveText('30s')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect(errors).toEqual([])
  })
}

test('mobile typing supports composition input, keyboard viewport and resuming from its menu', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await page.getByRole('tab', { name: /Typing Sprint/ }).click()
  await page.getByRole('button', { name: 'Play Typing Sprint', exact: true }).click()
  const field = page.getByRole('textbox', { name: 'Type the highlighted word' })
  const word = (await page.locator('.typing-target-word').getAttribute('aria-label'))!
  await field.dispatchEvent('compositionstart')
  await field.fill(word)
  await expect(page.locator('.typing-sprint-game')).toHaveAttribute('data-phase', 'ready')
  await field.dispatchEvent('compositionend', { data: word })
  await expect(page.locator('.typing-sprint-game')).toHaveAttribute('data-phase', 'running')
  await field.press('Enter')
  await expect(page.getByTestId('typing-score')).toHaveText(String(word.length + 1))
  await expect(page.getByTestId('typing-accuracy')).toHaveText('100%')
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport!, 'height', { configurable: true, get: () => 400 })
    window.visualViewport!.dispatchEvent(new Event('resize'))
  })
  await expect(page.locator('.typing-sprint-game')).toHaveClass(/typing-keyboard-open/)
  await expect.poll(async () => (await field.boundingBox())!.y + (await field.boundingBox())!.height).toBeLessThanOrEqual(376)
  const stats = await page.locator('.typing-hud').boundingBox()
  expect(stats!.y).toBeGreaterThanOrEqual(0)
  await page.screenshot({ path: '../.tools/typing-keyboard-390.png' })
  await page.getByRole('button', { name: 'Back to Typing Sprint menu' }).click()
  await expect(page.locator('.typing-board')).toBeHidden()
  const time = await page.getByTestId('typing-time').textContent()
  await page.waitForTimeout(1100)
  expect(await page.getByTestId('typing-time').textContent()).toBe(time)
  await page.getByRole('button', { name: 'Resume Typing Sprint', exact: true }).click()
  await expect(page.getByTestId('typing-score')).toHaveText(String(word.length + 1))
  await expect(field).toBeFocused()
})
