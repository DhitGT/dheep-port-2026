import { test, expect } from '@playwright/test'

test.use({ viewport: { width: 390, height: 900 }, hasTouch: true })

test('mobile games show a menu first and preserve tabs, HUD and progress during play', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await page.getByRole('tab', { name: /Physics Lab/ }).tap()
  await expect(page.getByRole('button', { name: 'Play Physics Lab' })).toBeVisible()
  await expect(page.locator('#physics-canvas')).toBeHidden()
  await page.getByRole('button', { name: 'Play Physics Lab' }).tap()
  await expect(page.locator('#physics-canvas canvas')).toBeVisible({ timeout: 15000 })
  for (const tab of await page.getByRole('tab').all()) await expect(tab).toBeVisible()
  await page.getByRole('tab', { name: /Bug Hunt/ }).tap()
  await expect(page.locator('.bug-board-wrap')).toBeHidden()
  await expect(page.locator('.bug-hunt-sidebar')).toBeVisible()
  await page.getByRole('button', { name: 'Play Bug Hunt', exact: true }).tap()
  await expect(page.locator('.bug-hunt-sidebar')).toBeHidden()
  await expect(page.locator('.bug-grid')).toBeVisible()
  await expect(page.getByTestId('bug-mobile-score')).toBeVisible()
  await expect(page.getByTestId('bug-mobile-time')).toBeVisible()
  await page.getByRole('button', { name: /Patch bug at slot/ }).first().tap()
  await expect(page.getByTestId('bug-mobile-score')).toHaveText('10')
  for (const tab of await page.getByRole('tab').all()) await expect(tab).toBeVisible()
  await page.getByRole('button', { name: 'Back to Bug Hunt menu' }).tap()
  await expect(page.locator('.bug-board-wrap')).toBeHidden()
  const remaining = await page.getByTestId('bug-mobile-time').textContent()
  await page.waitForTimeout(1100)
  expect(await page.getByTestId('bug-mobile-time').textContent()).toBe(remaining)
  await page.getByRole('button', { name: 'Resume Bug Hunt', exact: true }).tap()
  await expect(page.getByTestId('bug-mobile-score')).toHaveText('10')
  await page.getByRole('tab', { name: /Stack Merge/ }).tap()
  await expect(page.locator('.stack-board')).toBeHidden()
  await page.getByRole('button', { name: 'Play Stack Merge', exact: true }).tap()
  await expect(page.locator('.stack-board')).toBeVisible()
  await expect(page.locator('.stack-merge-sidebar')).toBeHidden()
  await expect(page.getByTestId('merge-mobile-score')).toBeVisible()
  await page.getByRole('button', { name: 'Back to Stack Merge menu' }).tap()
  await expect(page.locator('.stack-board')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Resume Stack Merge', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
