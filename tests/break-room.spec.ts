import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) {
  test(`Stack Merge drops, merges, pauses and resets at ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => { Math.random = () => .1 })
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
    await page.getByRole('tab', { name: /Stack Merge/ }).click()
    if (width < 800) await expect(page.locator('.stack-board')).toBeHidden()
    await page.getByRole('button', { name: width < 800 ? 'Play Stack Merge' : 'Start building', exact: true }).click()
    const score = page.getByTestId(width < 800 ? 'merge-mobile-score' : 'merge-score')
    if (width < 800) {
      await expect(page.locator('.stack-merge-sidebar')).toBeHidden()
      await expect(score).toBeVisible()
      for (const tab of await page.getByRole('tab').all()) await expect(tab).toBeVisible()
    }
    const board = page.locator('.stack-board')
    await board.focus()
    await board.press('Space')
    await expect(page.locator('.stack-merge-game')).toHaveAttribute('data-token-count', '1')
    await expect(page.getByRole('button', { name: 'Drop Bit', exact: false })).toBeEnabled()
    await board.press('Space')
    await expect(score).toHaveText('4', { timeout: 10000 })
    await expect(page.locator('.stack-merge-game')).toHaveAttribute('data-token-count', '1')
    await board.press('p')
    await expect(page.getByRole('button', { name: 'Resume build', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Resume build', exact: true }).click()
    await page.getByRole('tab', { name: /Bug Hunt/ }).click()
    await page.getByRole('tab', { name: /Stack Merge/ }).click()
    await expect(score).toHaveText('4')
    await page.getByRole('button', { name: 'Restart Stack Merge' }).click()
    await expect(score).toHaveText('0')
    await expect(page.locator('.stack-merge-game')).toHaveAttribute('data-token-count', '0')
    expect(await page.evaluate(() => localStorage.getItem('portfolio.stack-merge.best'))).toBe('4')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await page.mouse.move(0, 0)
    await page.locator('.stack-merge-game').screenshot({ path: `test-results/stack-merge-playing-${width}.png` })
    expect(errors).toEqual([])
  })
}

test('Bug Hunt scores correct patches, penalizes healthy code and finishes its timed round', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await page.getByRole('tab', { name: /Bug Hunt/ }).click()
  await page.getByRole('button', { name: 'Start Bug Hunt', exact: true }).click()
  await page.locator('.bug-grid').scrollIntoViewIfNeeded()
  await page.clock.install({ time: new Date('2026-10-16T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-16T00:00:01Z'))
  await page.getByRole('button', { name: /Patch bug at slot/ }).first().click()
  await expect(page.getByTestId('bug-score')).toHaveText('10')
  await page.getByRole('button', { name: /Healthy code at slot/ }).first().click()
  await expect(page.getByTestId('bug-score')).toHaveText('0')
  const remaining = await page.getByTestId('bug-time').textContent()
  await page.getByRole('tab', { name: /Physics Lab/ }).click()
  await page.clock.runFor(5000)
  expect(await page.getByTestId('bug-time').textContent()).toBe(remaining)
  await page.getByRole('tab', { name: /Bug Hunt/ }).click()
  await page.locator('.bug-grid').scrollIntoViewIfNeeded()
  await page.clock.runFor(34000)
  await expect(page.locator('.bug-hunt-game')).toHaveAttribute('data-state', 'finished')
  await expect(page.getByTestId('bug-time')).toHaveText('0s')
  await expect(page.getByRole('heading', { name: '1 bugs patched.' })).toBeVisible()
  await page.getByRole('button', { name: 'Play again', exact: true }).click()
  await expect(page.locator('.bug-hunt-game')).toHaveAttribute('data-state', 'playing')
  await expect(page.getByTestId('bug-time')).toHaveText('30s')
  expect(errors).toEqual([])
})
