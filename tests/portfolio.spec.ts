test('failed contact service never reports success and preserves the draft', async ({ page }) => {
  await page.route('**/api/contact', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Contact service unavailable."}' }))
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await page.locator('#contact').scrollIntoViewIfNeeded()
  await page.getByLabel('Name', { exact: true }).fill('Offline Visitor')
  await page.getByLabel('Email', { exact: true }).fill('offline@example.com')
  await page.getByLabel('Message', { exact: true }).fill('This draft should stay available when the API is offline.')
  await page.getByRole('button', { name: 'SEND TRANSMISSION' }).click()
  await expect(page.locator('form [role="status"]')).toContainText('Connection unavailable')
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Offline Visitor')
})
