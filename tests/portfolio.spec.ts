import { test, expect } from '@playwright/test'

test('custom cursor stays centered on the pointer across hover sizes and scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  async function checkCenter(x: number, y: number) {
    x = Math.round(x)
    y = Math.round(y)
    await page.mouse.move(x, y)
    await expect.poll(() => page.evaluate(({ x, y }) => {
      return Math.max(...['cursor-dot', 'cursor-outline'].map(id => {
        const rect = document.getElementById(id)!.getBoundingClientRect()
        return Math.max(Math.abs(rect.x + rect.width / 2 - x), Math.abs(rect.y + rect.height / 2 - y))
      }))
    }, { x, y })).toBeLessThan(0.75)
  }
  await checkCenter(200, 160)
  const button = await page.locator('a[href="#work"]').last().boundingBox()
  await checkCenter(button!.x + button!.width / 2, button!.y + button!.height / 2)
  await expect(page.locator('body')).toHaveClass(/hovering/)
  await expect.poll(async () => (await page.locator('#cursor-outline').boundingBox())!.width).toBeCloseTo(90, 0)
  await checkCenter(200, 160)
  await page.locator('.project-card-stack').first().scrollIntoViewIfNeeded()
  const project = await page.locator('.mission-img-box').first().boundingBox()
  await checkCenter(project!.x + project!.width / 2, project!.y + project!.height / 2)
  await expect(page.locator('body')).toHaveClass(/view-project/)
  await expect.poll(async () => (await page.locator('#cursor-outline').boundingBox())!.width).toBeCloseTo(120, 0)
  await page.evaluate(() => document.body.classList.add('god-mode'))
  await checkCenter(180, 150)
})

test('desktop portfolio loads without runtime errors and all images resolve', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (/Portfolio effects|[Hh]ydration/.test(message.text())) errors.push(message.text())
  })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await expect(page.locator('h1')).toContainText('BUILD')
  await expect(page).toHaveTitle('Aditya Dwi Saputra Nugraha | Software Developer')
  await expect(page.locator('#about')).toContainText('Aditya Dwi Saputra Nugraha')
  await expect(page.locator('#magnetic-btn')).toContainText('dheep.co@gmail.com')
  await expect(page.locator('#experience')).toContainText('PT Traspac Makmur Sejahtera')
  await expect(page.locator('.public-project-card')).toHaveCount(2)
  await expect(page.locator('.project-overview')).toHaveCount(3)
  await expect(page.locator('.project-card-stack')).toHaveCount(3)
  await expect(page.locator('.tagcloud-item')).toHaveCount(11)
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.fonts.check('700 48px Syncopate'))).toBeTruthy()
  for (const img of await page.locator('img').all()) {
    const src = await img.getAttribute('src')
    const response = await request.get(src!)
    expect(response.ok()).toBeTruthy()
    expect(response.headers()['content-type']).toContain('image/')
  }
  await expect(page.locator('a[href$=".pdf"]')).toHaveCount(0)
  await expect(page.locator('.public-project-link[href="https://github.com/DhitGT/secret-message"]')).toBeAttached()
  await expect(page.locator('.public-project-link[href="https://www.dheep.site/1945/"]')).toBeAttached()
  await expect(page.locator('body')).not.toContainText('SHIVAM')
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

