test('contact form sends a message through Nuxt to Laravel', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#loader')).toBeHidden({ timeout: 15000 })
  await page.locator('#contact').scrollIntoViewIfNeeded()
  await page.getByLabel('Name', { exact: true }).fill('Browser Test Visitor')
  await page.getByLabel('Email', { exact: true }).fill('browser-test@example.com')
  await page.getByLabel('Message', { exact: true }).fill('End-to-end test of the Nuxt and Laravel contact form.')
  const result = page.waitForResponse(response => response.url().endsWith('/api/contact') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'SEND TRANSMISSION' }).click()
  expect((await result).status()).toBe(201)
  await expect(page.locator('form [role="status"]')).toContainText('TRANSMISSION RECEIVED')
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('')
})

